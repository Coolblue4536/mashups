#!/usr/bin/env python3
"""Generate src/StellarAscension/Generated/Defs.g.cs from sheets/design.json: one C# record per row.

Refuses to run unless tools/preflight.py is clean. Column types are inferred from the cells.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import design  # noqa: E402

OUT = ROOT / "src" / "StellarAscension" / "Generated" / "Defs.g.cs"


def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in s.replace("-", "_").split("_") if p)


def singular(name):
    special = {"rules": "Rule", "space_race": "SpaceRace", "difficulties": "Difficulty", "map_sizes": "MapSize", "game_lengths": "GameLength",
               "yields": "Yield", "terrains": "Terrain", "features": "Feature", "natural_wonders": "NaturalWonder", "buildings": "Building",
               "wonders": "Wonder", "projects": "Project", "tech_legacy": "TechLegacy", "eras": "Era", "resources": "Resource",
               "star_classes": "StarClass", "planet_classes": "PlanetClass", "districts": "District", "planet_buildings": "PlanetBuilding",
               "ships": "Ship", "act2_techs": "Act2Tech", "modifiers": "Modifier", "aliens": "Alien", "asset_refs": "AssetRef",
               "game_systems": "GameSystem", "units": "Unit", "galaxy_sizes": "GalaxySize", "galaxy_difficulties": "GalaxyDifficulty", "civ_traits": "CivTrait", "civ_trait_map": "CivTraitMap", "exotic_sites": "ExoticSite", "preftl_techs": "PreftlTech", "improvements": "Improvement"}
    return special.get(name, pascal(name).rstrip("s"))


def cs_type(vals):
    if all(isinstance(v, bool) for v in vals):
        return "bool"
    if all(isinstance(v, list) for v in vals):
        return "string[]"
    if all(isinstance(v, int) and not isinstance(v, bool) for v in vals):
        return "int"
    if all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in vals):
        return "double"
    return "string"


def lit(v, t):
    if t == "bool":
        return "true" if v else "false"
    if t == "string[]":
        return "new[] { " + ", ".join(lit(x, "string") for x in v) + " }" if v else "System.Array.Empty<string>()"
    if t == "int":
        return str(v)
    if t == "double":
        return repr(float(v))
    s = str(v)
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    if subprocess.run([sys.executable, str(ROOT / "tools" / "preflight.py")], capture_output=True).returncode != 0:
        print("gen: preflight is not clean; run tools/preflight.py")
        return 1
    S = design.load()
    out = ["// <auto-generated> from sheets/design.json by tools/gen.py. Do not edit; edit the sheet. </auto-generated>",
           "#nullable enable", "namespace StellarAscension;", ""]
    rules = S.pop("rules")
    out.append("/// <summary>" + rules["about"].replace("&", "&amp;").replace("<", "&lt;") + "</summary>")
    out.append("public static class Rules")
    out.append("{")
    for r in rules["rows"]:
        out.append(f"    /// <summary>{r['desc'].replace('&', '&amp;').replace('<', '&lt;')}</summary>")
        out.append(f"    public const double {pascal(r['id'])} = {float(r['value'])!r};")
    out.append("}")
    out.append("")
    coll = []
    for name in design.ORDER:
        if name not in S:
            continue
        sh = S[name]
        rec, cols = singular(name) + "Def", sh["columns"]
        types = {c: cs_type([r[c] for r in sh["rows"]]) for c in cols}
        out.append("/// <summary>" + sh["about"].replace("&", "&amp;").replace("<", "&lt;") + "</summary>")
        out.append(f"public sealed record {rec}(" + ", ".join(f"{types[c]} {pascal(c)}" for c in cols) + ");")
        out.append("")
        coll.append((name, rec, cols, types, sh["rows"]))
    out.append("public static partial class Defs")
    out.append("{")
    for name, rec, cols, types, rows in coll:
        prop = pascal(name)
        out.append(f"    public static readonly {rec}[] {prop} =")
        out.append("    {")
        for r in rows:
            out.append("        new(" + ", ".join(lit(r[c], types[c]) for c in cols) + "),")
        out.append("    };")
        key = cols[0]
        lookup = singular(name) if singular(name) != prop else singular(name) + "ById"
        out.append(f"    public static readonly System.Collections.Generic.Dictionary<string, {rec}> {lookup} = "
                   f"System.Linq.Enumerable.ToDictionary({prop}, d => d.{pascal(key)});")
        out.append("")
    out.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"gen: wrote {OUT.relative_to(ROOT)} ({sum(len(c[4]) for c in coll) + len(rules['rows'])} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
